cat > run_quality_checks.sh <<'SCRIPT'
#!/usr/bin/env bash
set -Eeuo pipefail

PROJECT_DIR="${1:-$HOME/sppu/git/linux-system-monitor}"

if [[ ! -f "$PROJECT_DIR/CMakeLists.txt" ]]; then
    echo "ERROR: Project not found: $PROJECT_DIR"
    exit 1
fi

cd "$PROJECT_DIR"

# Check dependencies without installing packages automatically.
for tool in cmake ctest; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "ERROR: $tool is not installed."
        exit 1
    fi
done

if ! command -v clang-tidy >/dev/null 2>&1; then
    echo "ERROR: clang-tidy is not installed."
    echo "Install it with: sudo apt install clang-tidy"
    exit 1
fi

# Configure and build before testing and static analysis.
echo
echo "========== Configure CMake =========="
cmake -S . -B build \
    -DCMAKE_BUILD_TYPE=Debug \
    -DCMAKE_EXPORT_COMPILE_COMMANDS=ON

echo
echo "========== Build project =========="
cmake --build build --parallel

# Stop if tests fail.
echo
echo "========== Run Google Tests =========="
ctest --test-dir build --output-on-failure

# Use the compilation database generated by CMake.
echo
echo "========== Run Clang-Tidy =========="
sources=(
    src/main.cpp
    src/cpu.cpp
    src/memory.cpp
    src/uptime.cpp
    src/processes.cpp
)

for source in "${sources[@]}"; do
    if [[ ! -f "$source" ]]; then
        echo "ERROR: Missing source file: $source"
        exit 1
    fi
done

clang-tidy -p build "${sources[@]}"

# Update .gitignore without deleting existing rules.
echo
echo "========== Update .gitignore =========="
touch .gitignore

python3 <<'PY'
from pathlib import Path

p = Path(".gitignore")
content = p.read_text()
existing = set(content.splitlines())

required = [
    "/build/",
    "/build-asan/",
    "/cpu_check",
    "/uptime_process_check",
    "*.o",
]

added = [item for item in required if item not in existing]

if added:
    with p.open("a") as f:
        if content and not content.endswith("\n"):
            f.write("\n")
        f.write("\n".join(added) + "\n")
    print("Added:", ", ".join(added))
else:
    print("Required ignore patterns already exist.")
PY

echo
echo "========== Git status =========="
git status --short

echo
echo "Quality checks completed successfully."
SCRIPT

chmod +x run_quality_checks.sh

echo "========== Updating README.md =========="

cat > README.md <<'README'
# Linux System Monitor

A Linux system-monitoring utility written in **C++17** that reads system information from Linux's `/proc` virtual filesystem.

## Features

- **CPU monitoring:** Estimates CPU utilization using successive readings from `/proc/stat`.
- **Memory monitoring:** Reads total and available memory from `/proc/meminfo` and calculates estimated memory usage.
- **System uptime:** Reads uptime information from `/proc/uptime`.
- **Process enumeration:** Lists process IDs and names by inspecting `/proc` entries.
- **Unit testing:** Uses Google Test to validate parsing, calculations, invalid input handling, and missing-file scenarios.
- **Static analysis:** Supports Clang-Tidy.
- **Memory-error checking:** Supports AddressSanitizer builds.

## Tech Stack

- C++17
- Linux procfs
- CMake
- Google Test
- Clang-Tidy
- AddressSanitizer

